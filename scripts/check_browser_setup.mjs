import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'

const { chromium } = await import(pathToFileURL(process.env.DUCTDELTA_PLAYWRIGHT_MODULE).href)

const origin = process.env.DD_SETUP_ORIGIN
const browser = await chromium.launch({ executablePath: process.env.DUCTDELTA_CHROME ?? '/usr/bin/google-chrome' })
const errors = []
const button = (page, name) => page.getByRole('button', { name, exact: true })
const heading = (page, name) => page.getByRole('heading', { name, exact: true })
const link = (page, name) => page.getByRole('link', { name, exact: true })
const checkWidth = async (page) => assert.ok(await page.evaluate(
  () => document.documentElement.scrollWidth <= innerWidth
))
try {
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' })
  const phoneOptions = { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true }
  const phone = await browser.newContext(phoneOptions)
  const owner = await desktop.newPage()
  const member = await phone.newPage()
  for (const page of [owner, member]) {
    page.setDefaultTimeout(8000)
    page.on('pageerror', error => errors.push(String(error)))
  }
  await owner.goto(origin + '/workspace/')
  await heading(owner, 'Sign in to your workspace').waitFor()
  assert.ok(await owner.locator('html').evaluate(element => element.classList.contains('light')))
  await link(owner, 'About DuctDelta').click()
  await heading(owner, 'Every change. Accounted for.').waitFor()
  assert.equal(new URL(owner.url()).pathname, '/')
  await link(owner, 'Open workspace').first().click()
  await heading(owner, 'Sign in to your workspace').waitFor()
  assert.equal(new URL(owner.url()).pathname, '/workspace/')

  await button(owner, 'Create a company').click({ timeout: 5000 })
  await owner.getByLabel('Company name').fill('Basin Mechanical')
  await owner.getByLabel('Your name').fill('Ada Site')
  await button(owner, 'Create company').click()
  await heading(owner, 'Save your sign-in keys').waitFor()
  const accessKey = await owner.getByLabel('Access key', { exact: true }).inputValue()
  assert.equal(accessKey.length, 64)
  await button(owner, 'I saved my keys').click()
  await heading(owner, 'Projects').waitFor()
  const [basinMechanical] = await (await owner.request.get(origin + '/api/companies')).json()
  const lifetime = owner.getByRole('spinbutton', { name: 'Default invitation lifetime', exact: true })
  await lifetime.waitFor()
  assert.equal(await lifetime.inputValue(), '7')
  await lifetime.fill('2')
  await button(owner, 'Save lifetime').click()
  await owner.getByText('Invitation lifetime saved.', { exact: true }).waitFor()
  const accessHistory = owner.getByRole('region', { name: 'Recent access changes', exact: true })
  await accessHistory.getByText('7 days → 2 days', { exact: true }).waitFor()
  await owner.getByLabel('Project name').fill('Hospital plantroom')
  await button(owner, 'Create project').click()
  await owner.getByRole('link', { name: 'Hospital plantroom', exact: true }).waitFor()
  await owner.getByLabel('Invitee name').fill('Sam Site')
  await button(owner, 'Create invitation').click()
  const inviteInput = owner.getByLabel('Invitation link', { exact: true })
  await inviteInput.waitFor()
  await accessHistory.getByText('Invitation created', { exact: true }).waitFor()
  const invite = await inviteInput.inputValue()
  assert.ok(invite.startsWith(origin + '/workspace/#invite='))
  assert.equal(new URL(invite).hash.length, 72, 'The API returns a full token')
  assert.ok(/^[a-f0-9]{64}$/i.test(new URLSearchParams(new URL(invite).hash.slice(1)).get('invite')), 'Invitation token decodes as hex')
  await member.goto(invite)
  await heading(member, 'Join the company').waitFor()
  await member.waitForFunction(() => !location.hash)
  await member.reload()
  await heading(member, 'Join the company').waitFor()
  assert.equal(new URL(member.url()).hash, '')
  await button(member, 'Accept invitation').click()
  await heading(member, 'Save your sign-in keys').waitFor()
  const recoveryKey = await member.getByLabel('Recovery key', { exact: true }).inputValue()
  const memberKey = await member.getByLabel('Access key', { exact: true }).inputValue()
  await button(member, 'I saved my keys').click()
  await member.getByText('Your account has no assigned projects.', { exact: true }).waitFor()
  await button(member, 'Open sidebar').click()
  await button(member, 'Account menu, Sam Site').click()
  await member.getByRole('menuitem', { name: 'Account sessions', exact: true }).click()
  await heading(member, 'Active sessions').waitFor()
  await member.getByText('Current session', { exact: true }).waitFor()
  assert.equal(await button(member, 'Sign out all other sessions').count(), 0)
  await checkWidth(member)
  await member.screenshot({ path: 'artifacts/account-sessions-mobile.png', animations: 'disabled' })
  await member.goto(origin + '/workspace/')
  await button(owner, 'Refresh setup').click()
  await accessHistory.getByText('Invitation accepted', { exact: true }).waitFor()
  await owner.getByRole('listitem').filter({ hasText: 'Sam Site' }).getByRole('button', { name: 'Manage access' }).waitFor()
  await owner.screenshot({ path: 'artifacts/company-setup-desktop.png', animations: 'disabled' })
  await accessHistory.screenshot({ path: 'artifacts/company-access-history-desktop.png', animations: 'disabled' })
  await owner.getByRole('listitem').filter({ hasText: 'Sam Site' }).getByRole('button', { name: 'Manage access' }).click()
  await heading(owner, 'Manage access').waitFor()
  await owner.getByRole('combobox', { name: 'Project', exact: true }).click()
  await owner.getByRole('option', { name: 'Hospital plantroom', exact: true }).click()
  await owner.getByRole('combobox', { name: 'Project permission', exact: true }).click()
  await owner.getByRole('option', { name: 'Capture', exact: true }).click()
  await owner.getByRole('checkbox', { name: 'Certificates, payments and finance files', exact: true }).check()
  await button(owner, 'Save project access').click()
  await owner.getByText('Project access saved.', { exact: true }).waitFor()
  await member.reload()
  await heading(member, 'Project overview').waitFor()
  await member.getByText('Net certified balance', { exact: true }).waitFor()
  await member.goto(origin + '/product/')
  await link(member, 'Open workspace').first().click()
  await heading(member, 'Project overview').waitFor()
  await button(member, 'New observation').click()
  await member.getByLabel('Observation', { exact: true }).fill('A beam blocks the duct route.')
  await button(member, 'Save observation').click()
  await member.getByText('A beam blocks the duct route.', { exact: true }).first().waitFor()
  await checkWidth(member)
  await member.screenshot({ path: 'artifacts/company-setup-mobile.png', animations: 'disabled' })

  const blockedStorage = await browser.newContext(phoneOptions)
  await blockedStorage.addInitScript(() => {
    const setItem = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key === 'ductdelta-pending-invitation') throw new DOMException('Storage is blocked', 'SecurityError')
      setItem.call(this, key, value)
    }
  })
  const cancelled = await blockedStorage.newPage()
  await cancelled.goto(origin + '/#invite=' + process.env.DD_EXPIRED_INVITE)
  await heading(cancelled, 'Join the company').waitFor({ timeout: 8000 })
  assert.notEqual(new URL(cancelled.url()).hash, '')
  await button(cancelled, 'Cancel invitation').click()
  await cancelled.waitForFunction(() => !location.hash, undefined, { timeout: 8000 })
  await cancelled.reload()
  await heading(cancelled, 'Sign in to your workspace').waitFor()

  const signedOutPhone = await browser.newContext(phoneOptions)
  const existing = await signedOutPhone.newPage()
  existing.setDefaultTimeout(8000)
  existing.on('pageerror', error => errors.push(String(error)))
  const token = process.env.DD_SECOND_INVITE
  const secondInvite = origin + '/#invite=' + token
  const desktopRecipient = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  await desktopRecipient.goto(secondInvite)
  await button(desktopRecipient, 'Sign in to accept').click()
  await desktopRecipient.getByLabel('Access key', { exact: true }).fill(memberKey)
  await button(desktopRecipient, 'Sign in').click()
  await desktopRecipient.getByText('Accept this invitation as Sam Site.', { exact: true }).waitFor()
  await checkWidth(desktopRecipient)
  await desktopRecipient.screenshot({ path: 'artifacts/company-invitation-existing-desktop.png', animations: 'disabled' })
  await button(desktopRecipient, 'Cancel invitation').click()
  await heading(desktopRecipient, 'Project overview').waitFor()
  await desktopRecipient.close()

  const requestsWithToken = []
  existing.on('request', request => {
    const url = new URL(request.url())
    if (url.pathname.includes(token) || url.search.includes(token)
        || request.headers().referer?.includes(token) || request.postData()?.includes(token)) {
      requestsWithToken.push(url.pathname)
    }
  })
  await existing.goto(secondInvite)
  await heading(existing, 'Join the company').waitFor()
  await existing.waitForFunction(() => !location.hash)
  await button(existing, 'Sign in to accept').click()
  await existing.getByLabel('Access key', { exact: true }).fill('0'.repeat(64))
  await button(existing, 'Sign in').click()
  await existing.getByRole('alert').getByText('The access key is invalid.').waitFor()
  await existing.getByLabel('Access key', { exact: true }).fill(memberKey)
  await button(existing, 'Sign in').click()
  await existing.getByText('Accept this invitation as Sam Site.', { exact: true }).waitFor()
  await existing.reload()
  await existing.getByText('Accept this invitation as Sam Site.', { exact: true }).waitFor()
  await signedOutPhone.clearCookies()
  await button(existing, 'Accept invitation').click()
  await existing.getByRole('alert').getByText('Your session ended. Sign in again to accept this invitation.').waitFor()
  await existing.getByLabel('Access key', { exact: true }).fill('0'.repeat(64))
  await button(existing, 'Sign in').click()
  await existing.getByRole('alert').getByText('The access key is invalid.').waitFor()
  await existing.getByLabel('Access key', { exact: true }).fill(memberKey)
  await button(existing, 'Sign in').click()
  await existing.getByText('Accept this invitation as Sam Site.', { exact: true }).waitFor()
  await checkWidth(existing)
  await existing.screenshot({ path: 'artifacts/company-invitation-existing-mobile.png', animations: 'disabled' })
  assert.deepEqual(requestsWithToken, ['/api/invitations/accept'])
  const originalMembership = { ...basinMechanical, role: 'member' }
  assert.deepEqual(await (await existing.request.get(origin + '/api/companies')).json(), [originalMembership])
  await button(existing, 'Accept invitation').click()
  await heading(existing, 'Project overview').waitFor()
  const companyList = await (await existing.request.get(origin + '/api/companies')).json()
  assert.deepEqual(companyList, [
    originalMembership,
    { id: process.env.DD_SECOND_COMPANY, name: 'West Mechanical', role: 'admin' }
  ])
  assert.deepEqual(requestsWithToken, ['/api/invitations/accept', '/api/invitations/accept'])
  await existing.reload()
  await heading(existing, 'Project overview').waitFor()

  const expired = await browser.newContext(phoneOptions)
  const recipient = await expired.newPage()
  await recipient.goto(origin + '/#invite=' + process.env.DD_EXPIRED_INVITE)
  await heading(recipient, 'Join the company').waitFor()
  const rejected = recipient.waitForResponse(response => response.url() === origin + '/api/invitations/accept')
  await button(recipient, 'Accept invitation').click()
  assert.equal((await rejected).status(), 404)
  await recipient.getByRole('alert').getByText('This invitation has expired, was cancelled, or has already been used.').waitFor()
  await checkWidth(recipient)
  await recipient.screenshot({ path: 'artifacts/company-invitation-expired-mobile.png', animations: 'disabled' })
  await button(recipient, 'Cancel invitation').click()
  await recipient.reload()
  await heading(recipient, 'Sign in to your workspace').waitFor()

  await button(owner, 'Remove from company').click()
  await button(owner, 'Confirm removal').click()
  await owner.getByText('Company access removed.', { exact: true }).waitFor()
  await member.reload()
  await member.getByText('This project is unavailable. Select a project to continue.', { exact: true }).waitFor()
  assert.deepEqual(await (await existing.request.get(origin + '/api/companies')).json(), [companyList[1]])
  await owner.keyboard.press('Escape')
  await accessHistory.getByText('Company member removed', { exact: true }).waitFor()
  const newDevice = await browser.newPage()
  await newDevice.goto(origin + '/workspace/')
  await button(newDevice, 'Recover access').click()
  await newDevice.getByLabel('Recovery key', { exact: true }).fill(recoveryKey)
  await button(newDevice, 'Recover account').click()
  await heading(newDevice, 'Save your sign-in keys').waitFor()
  await checkWidth(owner)
  await owner.keyboard.press('Escape')
  await owner.setViewportSize({ width: 390, height: 844 })
  await heading(owner, 'Projects').waitFor()
  await checkWidth(owner)
  await heading(owner, 'Projects').scrollIntoViewIfNeeded()
  await owner.screenshot({ path: 'artifacts/company-settings-mobile.png', animations: 'disabled', mask: [inviteInput], maskColor: '#18181b' })
  await accessHistory.evaluate((section) => {
    section.style.scrollMarginTop = '5rem'
    section.scrollIntoView({ block: 'start', behavior: 'instant' })
    section.style.removeProperty('scroll-margin-top')
  })
  await owner.screenshot({ path: 'artifacts/company-access-history-mobile.png', animations: 'disabled', mask: [inviteInput], maskColor: '#18181b' })

  // The server commits registration, but Chrome never receives the credentials.
  const interrupted = await browser.newPage()
  interrupted.setDefaultTimeout(8000)
  await interrupted.route('**/api/companies', async (route) => {
    if (route.request().method() !== 'POST') {
      await route.continue()
      return
    }
    const response = await route.fetch()
    assert.equal(response.status(), 201)
    await route.abort('failed')
  })
  await interrupted.goto(origin + '/workspace/')
  await button(interrupted, 'Create a company').click()
  await interrupted.getByLabel('Company name').fill('Interrupted Mechanical')
  await interrupted.getByLabel('Your name').fill('Recovery admin')
  await button(interrupted, 'Create company').click()
  await heading(interrupted, 'Recover your account').waitFor()
  assert.equal((await interrupted.getByLabel('Recovery key', { exact: true }).inputValue()).length, 64)
  await interrupted.reload()
  await heading(interrupted, 'Recover your account').waitFor()
  await button(interrupted, 'Recover account').click()
  await heading(interrupted, 'Save your sign-in keys').waitFor()
  await button(interrupted, 'I saved my keys').click()
  await interrupted.getByRole('link', { name: 'Company settings', exact: true }).click()
  await heading(interrupted, 'Interrupted Mechanical').waitFor()

  await owner.setViewportSize({ width: 1440, height: 1000 })
  const otherOwners = [await browser.newContext(), await browser.newContext()]
  for (const context of otherOwners) {
    const login = await context.request.post(origin + '/api/session', { data: { key: accessKey }, headers: { Origin: origin } })
    assert.equal(login.status(), 204)
  }
  const sessionsPath = origin + '/api/account/sessions'
  const [signedInSecond] = await (await otherOwners[0].request.get(sessionsPath)).json()
  await button(owner, 'Account menu, Ada Site').click()
  await owner.getByRole('menuitem', { name: 'Account sessions', exact: true }).click()
  await heading(owner, 'Active sessions').waitFor()
  await owner.getByText('Current session', { exact: true }).waitFor()
  await checkWidth(owner)
  await owner.screenshot({ path: 'artifacts/account-sessions-desktop.png', animations: 'disabled' })
  const targetSession = owner.getByRole('listitem').filter({ hasText: 'Session ' + signedInSecond.id.slice(0, 8) })
  await targetSession.getByRole('button', { name: 'Sign out', exact: true }).click()
  await button(owner, 'Confirm sign-out').click()
  await owner.getByText('Session signed out.', { exact: true }).waitFor()
  assert.equal((await otherOwners[0].request.get(sessionsPath)).status(), 401)
  assert.equal((await otherOwners[1].request.get(sessionsPath)).status(), 200)
  await owner.setViewportSize({ width: 390, height: 844 })
  await button(owner, 'Sign out all other sessions').waitFor()
  await checkWidth(owner)
  await owner.screenshot({ path: 'artifacts/account-sessions-revoke-mobile.png', animations: 'disabled' })
  await button(owner, 'Sign out all other sessions').click()
  await button(owner, 'Confirm sign-out').click()
  await owner.getByText('Other sessions signed out.', { exact: true }).waitFor()
  assert.equal((await otherOwners[1].request.get(sessionsPath)).status(), 401)
  await owner.reload()
  await owner.getByText('Current session', { exact: true }).waitFor()
  assert.equal(await button(owner, 'Sign out all other sessions').count(), 0)
  assert.deepEqual(errors, [])
  console.log('PASS: Chrome company setup, invitation lifetime, access history, new and existing invitations, expired-link rejection, project access, capture, recovery and account sessions')
} finally {
  await browser.close()
}
