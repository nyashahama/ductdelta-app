import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'

const { chromium } = await import(pathToFileURL(process.env.DUCTDELTA_PLAYWRIGHT_MODULE).href)

const origin = process.env.DD_SETUP_ORIGIN
const browser = await chromium.launch({ executablePath: process.env.DUCTDELTA_CHROME ?? '/usr/bin/google-chrome' })
const errors = []
const button = (page, name) => page.getByRole('button', { name, exact: true })
const heading = (page, name) => page.getByRole('heading', { name, exact: true })
const checkWidth = async (page) => assert.ok(await page.evaluate(
  () => document.documentElement.scrollWidth <= innerWidth
))

try {
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const owner = await desktop.newPage()
  const member = await phone.newPage()
  for (const page of [owner, member]) {
    page.setDefaultTimeout(8000)
    page.on('pageerror', error => errors.push(String(error)))
  }
  await owner.goto(origin)
  await button(owner, 'Create a company').click({ timeout: 5000 })
  await owner.getByLabel('Company name').fill('Basin Mechanical')
  await owner.getByLabel('Your name').fill('Ada Site')
  await button(owner, 'Create company').click()
  await heading(owner, 'Save your sign-in keys').waitFor()
  const accessKey = await owner.getByLabel('Access key', { exact: true }).inputValue()
  assert.equal(accessKey.length, 64)
  await button(owner, 'I saved my keys').click()
  await heading(owner, 'Projects').waitFor()
  await owner.getByLabel('Project name').fill('Hospital plantroom')
  await button(owner, 'Create project').click()
  await owner.getByRole('link', { name: 'Hospital plantroom', exact: true }).waitFor()
  await owner.getByLabel('Invitee name').fill('Sam Site')
  await button(owner, 'Create invitation').click()
  const inviteInput = owner.getByLabel('Invitation link', { exact: true })
  await inviteInput.waitFor()
  const invite = await inviteInput.inputValue()
  assert.ok(invite.startsWith(origin + '/#invite='))
  assert.equal(new URL(invite).hash.length, 72, 'The API returns a full token')
  assert.ok(/^[a-f0-9]{64}$/i.test(new URLSearchParams(new URL(invite).hash.slice(1)).get('invite')), 'Invitation token decodes as hex')
  await member.goto(invite)
  await heading(member, 'Join the company').waitFor()
  await member.waitForFunction(() => !location.hash)
  await member.reload()
  await heading(member, 'Join the company').waitFor()
  assert.equal(new URL(member.url()).hash, '')
  await button(member, 'Accept invitation').click()
  await heading(member, 'Save your sign-in keys').waitFor()
  const recoveryKey = await member.getByLabel('Recovery key', { exact: true }).inputValue()
  await button(member, 'I saved my keys').click()
  await member.getByText('Your account has no assigned projects.', { exact: true }).waitFor()
  await button(owner, 'Refresh setup').click()
  await owner.getByRole('listitem').filter({ hasText: 'Sam Site' }).getByRole('button', { name: 'Manage access' }).waitFor()
  await owner.screenshot({ path: 'artifacts/company-setup-desktop.png', animations: 'disabled' })
  await owner.getByRole('listitem').filter({ hasText: 'Sam Site' }).getByRole('button', { name: 'Manage access' }).click()
  await heading(owner, 'Manage access').waitFor()
  await owner.getByRole('combobox', { name: 'Project', exact: true }).click()
  await owner.getByRole('option', { name: 'Hospital plantroom', exact: true }).click()
  await owner.getByRole('combobox', { name: 'Project permission', exact: true }).click()
  await owner.getByRole('option', { name: 'Capture', exact: true }).click()
  await owner.getByRole('checkbox', { name: 'Certificates, payments and finance files', exact: true }).check()
  await button(owner, 'Save project access').click()
  await owner.getByText('Project access saved.', { exact: true }).waitFor()
  await member.reload()
  await heading(member, 'Project overview').waitFor()
  await member.getByText('Net certified balance', { exact: true }).waitFor()
  await button(member, 'New observation').click()
  await member.getByLabel('Observation', { exact: true }).fill('A beam blocks the duct route.')
  await button(member, 'Save observation').click()
  await member.getByText('A beam blocks the duct route.', { exact: true }).first().waitFor()
  await checkWidth(member)
  await member.screenshot({ path: 'artifacts/company-setup-mobile.png', animations: 'disabled' })
  await button(owner, 'Remove from company').click()
  await button(owner, 'Confirm removal').click()
  await owner.getByText('Company access removed.', { exact: true }).waitFor()
  await member.reload()
  await member.getByText('This project is unavailable. Select a project to continue.', { exact: true }).waitFor()
  await owner.keyboard.press('Escape')
  await owner.getByLabel('Invitee name').fill('Sam Site')
  await button(owner, 'Create invitation').click()
  await member.goto(await inviteInput.inputValue())
  await member.getByText('Accept this invitation with your current DuctDelta account.', { exact: true }).waitFor()
  await button(member, 'Accept invitation').click()
  await member.getByText('Your account has no assigned projects.', { exact: true }).waitFor()
  const newDevice = await browser.newPage()
  await newDevice.goto(origin)
  await button(newDevice, 'Recover access').click()
  await newDevice.getByLabel('Recovery key', { exact: true }).fill(recoveryKey)
  await button(newDevice, 'Recover account').click()
  await heading(newDevice, 'Save your sign-in keys').waitFor()
  await checkWidth(owner)
  await owner.keyboard.press('Escape')
  await owner.setViewportSize({ width: 390, height: 844 })
  await heading(owner, 'Projects').waitFor()
  await checkWidth(owner)
  await owner.screenshot({ path: 'artifacts/company-settings-mobile.png', animations: 'disabled', mask: [inviteInput], maskColor: '#18181b' })

  // The server commits registration, but Chrome never receives the credentials.
  const interrupted = await browser.newPage()
  interrupted.setDefaultTimeout(8000)
  await interrupted.route('**/api/companies', async (route) => {
    if (route.request().method() !== 'POST') {
      await route.continue()
      return
    }
    const response = await route.fetch()
    assert.equal(response.status(), 201)
    await route.abort('failed')
  })
  await interrupted.goto(origin)
  await button(interrupted, 'Create a company').click()
  await interrupted.getByLabel('Company name').fill('Interrupted Mechanical')
  await interrupted.getByLabel('Your name').fill('Recovery admin')
  await button(interrupted, 'Create company').click()
  await heading(interrupted, 'Recover your account').waitFor()
  assert.equal((await interrupted.getByLabel('Recovery key', { exact: true }).inputValue()).length, 64)
  await interrupted.reload()
  await heading(interrupted, 'Recover your account').waitFor()
  await button(interrupted, 'Recover account').click()
  await heading(interrupted, 'Save your sign-in keys').waitFor()
  await button(interrupted, 'I saved my keys').click()
  await interrupted.getByRole('link', { name: 'Company settings', exact: true }).click()
  await heading(interrupted, 'Interrupted Mechanical').waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: Chrome company setup from an empty database, smartphone invite acceptance, project access, capture, revocation and interrupted-registration recovery')
} finally {
  await browser.close()
}
